#!/usr/bin/env python3
"""Build index-extra.js: corrections, related-title franchises, advertisers and companies for Browse.

usage: python3 scripts/indexing/build-index.py [repo root]
Reads the reader's own data plus scripts/indexing/data/*.json; writes <root>/assets/data/index-extra.js and index-related.js.
"""
import json, os, re, sys, unicodedata
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import load_issue, CATEGORY_OF
import ads_interactive, ads_archive
from index_curation import RENAME, BY_ID, FRANCHISES
from advertisers import A

root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..'))

def jsnorm(s):  # same as normalize() in titles.js
    s = unicodedata.normalize('NFKD', s)
    s = ''.join(c for c in s if not unicodedata.combining(c)).lower().replace('’', "'").replace('‘', "'")
    return re.sub(r'[^a-z0-9]+', ' ', s).strip()

titles = json.loads(re.search(r'window\.TITLES=(\[.*\])', open(os.path.join(root, 'assets', 'data', 'titles-data.js'), encoding='utf-8').read(), re.S).group(1))
rename = {k: v for k, v in RENAME.items() if k != v}
corrected = {t['id']: BY_ID.get(t['id'], {}).get('title') or rename.get(t['title'], t['title']) for t in titles}

# Franchises -> exact entry ids, so the browser does no fuzzy matching.
franchises = {}
for name, patterns in FRANCHISES.items():
    def hit(title, p):
        t = jsnorm(title)
        return t == jsnorm(p[1:]) if p.startswith('=') else t == jsnorm(p) or t.startswith(jsnorm(p) + ' ')
    ids = [t['id'] for t in titles if any(hit(corrected[t['id']], p) for p in patterns)]
    if len(ids) > 1: franchises[name] = ids
    elif ids: print(f'  franchise "{name}" matched only one entry; skipped')
    else: print(f'  franchise "{name}" matched nothing; check its patterns')

# Advertisers.
ads, media = [], {}
raw = ads_archive.ads(root) + ads_interactive.ads(root)
per_page = Counter((a['issue'], a['ref']) for a in raw)
seen = Counter()
for a in raw:
    d = load_issue(root, a['issue'])
    k = (a['issue'], a['ref']); seen[k] += 1
    cat = 'Video ads' if a['source'] == 'clip' else ads_archive.category(a['advertiser']) if a['advertiser'] != 'Unidentified advertiser' else 'Unidentified'
    note = a.get('note') or ('Advertisement' if per_page[k] == 1 else f'Advertisement (shared page, {per_page[k]} advertisers)')
    ads.append(dict(id=f"ad:{a['issue']}:{a['ref']}:{seen[k]}", kind='ads', title=a['advertiser'], headline=cat,
                    issue=a['issue'], date=d['date'], page=a['ref'], href=f"issues/{a['issue']}/index.html#page={a['ref']}",
                    image=a['image'], note=note))
    if a['image'] and a['image'] in (d.get('localAssets') or {}):
        media[a['image']] = d['localAssets'][a['image']]

# Companies (from scripts/indexing/data/companies.json when present).
companies = []
cpath = os.path.join(HERE, 'data', 'companies.json')
if os.path.exists(cpath):
    for c in json.load(open(cpath)):
        d = load_issue(root, c['issue'])
        companies.append(dict(id=f"co:{c['issue']}:{c['ref']}:{jsnorm(c['company'])[:24]}", kind='companies', title=c['company'],
                              headline=c.get('category') or CATEGORY_OF.get(c['company'], 'Other'), issue=c['issue'], date=d['date'],
                              page=c['ref'], href=f"issues/{c['issue']}/index.html#page={c['ref']}", image=c.get('image'),
                              note=c.get('note') or f"{c.get('mentions', 1)} mentions in “{c.get('article', 'article')}”"))
        if c.get('image') and c['image'] in (d.get('localAssets') or {}):
            media[c['image']] = d['localAssets'][c['image']]

byid = {k: v for k, v in BY_ID.items() if any(t['id'] == k for t in titles)}
IA = 'https://archive.org/download/'
def short(u): return u[len(IA):] if u and u.startswith(IA) else (u or '')
def pack(entries):
    """Compact rows: [issue, page, nameIndex, image, note]; names as [title, category]; expanded by titles.js."""
    names, index, rows = [], {}, []
    for e in entries:
        k = (e['title'], e['headline'])
        if k not in index: index[k] = len(names); names.append(list(k))
        rows.append([e['issue'], e['page'], index[k], short(e['image']), '' if e['note'] == 'Advertisement' else e['note']])
    return {'names': names, 'rows': rows}
names = {row['title'] for row in ads + companies}
aliases = {name: values[1] for name, values in A.items() if name in names and values[1]}
data = dict(version=1, ia=IA, rename=rename, byId=byid, franchises=franchises, ads=pack(ads), companies=pack(companies), aliases=aliases,
            dates={str(n): load_issue(root, n)['date'] for n in range(1, 173)})
packed_media = {short(u): [m['path'], m['name'], m['size'], m['crc']] for u, m in media.items()}
out = os.path.join(root, 'assets', 'data', 'index-extra.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/indexing/build-index.py: corrections, related titles, advertisers and companies for Browse.\n')
    f.write('window.CINEFEX_INDEX=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    f.write('(()=>{const ia=window.CINEFEX_INDEX.ia,m=' + json.dumps(packed_media, separators=(',', ':')) +
            ';const s=window.BROWSE_SOURCES=window.BROWSE_SOURCES||{};for(const u in m){const [path,name,size,crc]=m[u];s[ia+u]={path,name,size,crc}}})();\n')
# Per-story links for the reader's Contents panel: index-related.js
related = {}
ref_of = {t['id']: re.search(r'#page=(.+)$', t['href']).group(1) for t in titles}
story_at = {}
for n in range(1, 173):
    d = load_issue(root, n)
    for st in d['stories']:
        if isinstance(st.get('article'), int) and st['article'] < len(d['pages']):
            story_at[(n, d['pages'][st['article']]['ref'])] = st['article']
for name, ids in franchises.items():
    for i in ids:
        t = next(x for x in titles if x['id'] == i)
        a = story_at.get((t['issue'], ref_of[i]))
        if a is None: continue
        f = related.setdefault(str(t['issue']), {}).setdefault(str(a), {}).setdefault('f', [])
        if name not in f: f.append(name)
if os.path.exists(cpath):
    by_story = {}
    for c in json.load(open(cpath)):
        d = load_issue(root, c['issue'])
        st = next((s for s in d['stories'] if s['title'] == c['article']), None)
        if st and isinstance(st.get('article'), int): by_story.setdefault((c['issue'], st['article']), []).append(c)
    for (n, a), cs in by_story.items():
        related.setdefault(str(n), {}).setdefault(str(a), {})['c'] = [c['company'] for c in sorted(cs, key=lambda c: -c['mentions'])[:6]]
with open(os.path.join(root, 'assets', 'data', 'index-related.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/indexing/build-index.py: related titles and companies for each story.\n')
    f.write('window.CINEFEX_RELATED=' + json.dumps(related, ensure_ascii=False, separators=(',', ':')) + ';\n')

adv = Counter(a['title'] for a in ads)
print(f"index-extra.js: {len(ads)} ads from {len(adv)} advertisers ({adv['Unidentified advertiser']} unidentified), "
      f"{len(companies)} company entries, {len(franchises)} franchises, {len(rename) + len(byid)} title fixes, "
      f"{os.path.getsize(out) / 1e6:.1f} MB")
